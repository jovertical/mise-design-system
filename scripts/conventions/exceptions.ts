/**
 * Where a rule of the clean-code check does not apply, each with its reason.
 * A pattern matches a repository-relative path; `*` stands for any characters
 * within one path segment.
 */
import type { Rule, Violation } from './index.js'

const STORIES = 'src/lib/components/*/*/*.stories.svelte'
const STORY_REASON = 'The story skeleton makes a story file long by design'
const PALETTE = 'src/lib/tokens/tailwind-palette.ts'
const PALETTE_REASON = 'Generated by scripts/copy-tailwind-palette.ts'

export const EXCEPTIONS: Record<Rule, Record<string, string>> = {
  'file-length': { [STORIES]: STORY_REASON, [PALETTE]: PALETTE_REASON },
  'function-length': { [STORIES]: STORY_REASON },
  'non-null': {},
  names: {},
  spacing: { [PALETTE]: PALETTE_REASON },
}

export function isExcepted(violation: Violation) {
  return Object.keys(EXCEPTIONS[violation.rule]).some((pattern) => matches(pattern, violation.path))
}

function matches(pattern: string, path: string) {
  const expression = pattern
    .split('*')
    .map((part) => part.replace(/[.+?^${}()|[\]\\]/g, '\\$&'))
    .join('[^/]*')

  return new RegExp(`^${expression}$`).test(path)
}
